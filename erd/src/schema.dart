library;

class Col {
  final String name;
  final String type;
  final String kind; // 'pk' | 'fk' | 'plain'
  final String? ref; // FK target table (kind == 'fk')
  final bool dep; // DEPRECATED / unused column
  final bool mig; // added by a migration (not in setup.sql)
  const Col(this.name, this.type, [this.kind = 'plain', this.ref, this.dep = false, this.mig = false]);

  /// Type shown in the diagram. When a domain shares its column name the
  /// domain name is redundant, so it renders as ENUM.
  String get displayType => type == name ? 'ENUM' : type;
}

Col pk(String n, String t) => Col(n, t, 'pk');
Col fk(String n, String t, String ref) => Col(n, t, 'fk', ref);
Col c(String n, String t) => Col(n, t);
Col dep(String n, String t) => Col(n, t, 'plain', null, true);
Col mig(String n, String t) => Col(n, t, 'plain', null, false, true);
Col fkMig(String n, String t, String ref) => Col(n, t, 'fk', ref, false, true);

class Tbl {
  final String name;
  final List<Col> cols;
  const Tbl(this.name, this.cols);
}

